  static String codeForLocation(String location) {
    final country = location.split(',').last.trim();
    return CurrencyConversionHelper.countryByName(country)
            ?.code
            .toLowerCase() ??
        '';
  }

  static String codeFromEmoji(String flag) {
    final runes = flag.runes.toList();
    if (runes.length != 2 || runes.any((r) => r < 0x1F1E6 || r > 0x1F1FF))
      return '';
    return String.fromCharCodes(runes.map((r) => r - 0x1F1E6 + 97));
  }

  @override
  Widget build(BuildContext context) {
    final normalized = code.trim().toLowerCase();
    final fallback = ColoredBox(
        color: Theme.of(context).colorScheme.surfaceContainerHighest,
        child: Icon(Icons.public_rounded,
            size: size * .65,
            color: Theme.of(context).colorScheme.onSurfaceVariant));
    return Semantics(
        label: normalized.isEmpty ? tr('Country') : normalized.toUpperCase(),
        image: true,
        child: Container(
            width: size,
            height: size,
            decoration: BoxDecoration(
                shape: BoxShape.circle,
                border: Border.all(
                    color:
                        Theme.of(context).dividerColor.withValues(alpha: .3))),
            child: ClipOval(
                child: supportedCodes.contains(normalized)
                    ? Image.asset('assets/images/flags/$normalized.png',
                        width: size,
                        height: size,
                        fit: BoxFit.cover,
                        errorBuilder: (_, __, ___) => fallback)
                    : fallback)));
  }
